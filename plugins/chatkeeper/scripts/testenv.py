"""Изоляция тестов: своя папка данных каждому тестовому файлу.

Пути к данным (DATA, STATE, ENV_FILE) common.py вычисляет один раз при первом
импорте, а setup.py, source_bot.py и history.py забирают их к себе константами.
Для продукта это верно: каждая команда - отдельный процесс, переменная окружения
задана до его запуска и больше не меняется.

Для тестов это ловушка. В общем прогоне все тестовые файлы живут в одном процессе:
первый из них импортирует common и закрепляет свою временную папку, остальные
меняют переменную окружения уже впустую. Дальше родительский процесс читает
состояние из чужой папки, а дочерние процессы пишут в свою - и тесты падают
по причине, которой в продукте нет.

Лечение: перед импортом модулей продукта выкинуть их из списка загруженных.
Следующий импорт пересчитает пути и возьмёт папку того файла, который грузится
сейчас. Каждый тестовый файл получает собственные копии модулей продукта со
своими путями, и порядок загрузки перестаёт значить что-либо.

Продуктовый код при этом не трогается: ленивые пути понадобились бы только ради
тестов, а платил бы за них весь остальной код.
"""

from __future__ import annotations

import os
import sys
import tempfile
from pathlib import Path

SCRIPTS = Path(__file__).resolve().parent


def product_modules() -> set[str]:
    """Модули продукта: всё в этой папке, кроме тестов и самого этого файла.

    Список собирается по папке, а не переписывается руками: новый скрипт продукта
    однажды забыли бы дописать, и изоляция тихо перестала бы работать именно
    для него. Имена тестов и testenv начинаются на test - по этому и отсеиваем.
    """
    return {
        path.stem for path in SCRIPTS.glob("*.py") if not path.name.startswith("test")
    }


def isolate(prefix: str) -> str:
    """Отдельная папка данных для тестового файла.

    Вызывать ДО импорта модулей продукта: после импорта пути уже закреплены.
    """
    temp = tempfile.mkdtemp(prefix=prefix)
    os.environ["CHATKEEPER_DATA"] = temp
    for name in product_modules() & set(sys.modules):
        del sys.modules[name]
    return temp
